create table user_account (
  id bigint generated by default as identity primary key,
  email varchar(200) not null unique,
  name varchar(120) not null,
  password_hash varchar(100) not null,
  created_at timestamp not null
);

create table saved_plan (
  id bigint generated by default as identity primary key,
  user_id bigint not null references user_account(id),
  name varchar(120) not null,
  household_json text not null,
  success_rate double precision,
  safe_spending double precision,
  updated_at timestamp not null
);
create index saved_plan_user on saved_plan(user_id);

create table waitlist_entry (
  id bigint generated by default as identity primary key,
  email varchar(200) not null unique,
  first_name varchar(80),
  age_band varchar(20),
  assets_band varchar(20),
  status varchar(30),
  interests varchar(300),
  code varchar(12) not null unique,
  referred_by varchar(12),
  plan_summary text,
  source varchar(120),
  created_at timestamp not null
);

create table advisor_request (
  id bigint generated by default as identity primary key,
  user_id bigint,
  name varchar(120) not null,
  email varchar(200) not null,
  phone varchar(40),
  topic varchar(60) not null,
  message varchar(1000),
  created_at timestamp not null
);

create table quote_request (
  id bigint generated by default as identity primary key,
  user_id bigint,
  email varchar(200) not null,
  kind varchar(30) not null,
  premium double precision not null,
  age integer not null,
  state varchar(2),
  created_at timestamp not null
);
